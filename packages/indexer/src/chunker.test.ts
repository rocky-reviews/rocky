import { createHash } from "node:crypto";
import { INDEX_VECTOR_DIMENSIONS } from "@rocky-reviews/core";
import { beforeAll, describe, expect, it } from "vitest";
import { createTreeSitterChunker, gitBlobSha, prepareFile, type FileChunker } from "./chunker.js";
import { deterministicEmbedder } from "./deterministic-embedder.js";

const bytes = (text: string) => new TextEncoder().encode(text);

let chunker: FileChunker;
beforeAll(async () => {
  chunker = await createTreeSitterChunker();
});

const kinds = async (path: string, text: string) => {
  const prepared = await prepareFile(chunker, path, bytes(text));
  if (prepared.kind !== "chunks") throw new Error(`expected chunks, got ${prepared.reason}`);
  return prepared.chunks.map((c) => [c.startLine, c.endLine, c.kind]);
};

describe("tree-sitter chunks per language (real grammars, exact versions)", () => {
  it("TypeScript: functions, classes, interfaces and exported declarations", async () => {
    const text = [
      'import { z } from "zod";',
      "",
      "export interface User {",
      "  id: string;",
      "  name: string;",
      "}",
      "",
      "export function greet(user: User): string {",
      "  const name = user.name.trim();",
      "  return `hello ${name}`;",
      "}",
      "",
      "export class Store {",
      "  private users = new Map<string, User>();",
      "  add(user: User) {",
      "    this.users.set(user.id, user);",
      "  }",
      "}",
    ].join("\n");
    expect(await kinds("src/user.ts", text)).toEqual([
      [1, 6, "export_statement"],
      [8, 11, "export_statement"],
      [13, 18, "export_statement"],
    ]);
  });

  it("TSX, JavaScript, Python, Go, Rust and Java parse into their own unit types", async () => {
    const cases: [string, string, string][] = [
      [
        "web/App.tsx",
        "export function App() {\n  const a = 1;\n  return <div>{a}</div>;\n}\n",
        "export_statement",
      ],
      [
        "web/x.js",
        "function f(a) {\n  a += 1;\n  a *= 2;\n  return a;\n}\n",
        "function_declaration",
      ],
      [
        "t/run.py",
        "def run(x):\n    y = x + 1\n    z = y * 2\n    return z\n",
        "function_definition",
      ],
      [
        "cmd/main.go",
        "package main\n\nfunc main() {\n\tx := 1\n\ty := x + 1\n\tprintln(y)\n}\n",
        "function_declaration",
      ],
      [
        "src/lib.rs",
        "fn add(a: i32, b: i32) -> i32 {\n    let c = a + b;\n    c\n}\n",
        "function_item",
      ],
      [
        "src/A.java",
        "class A {\n  int f(int x) {\n    int y = x + 1;\n    return y;\n  }\n}\n",
        "class_declaration",
      ],
    ];
    for (const [path, text, kind] of cases) {
      const found = await kinds(path, text);
      expect(
        found.map((k) => k[2]),
        path,
      ).toContain(kind);
    }
  });

  it("falls back to line windows for text it does not parse, and when parsing gives up", async () => {
    expect(await kinds("README.md", "# Title\n\nSome words.\n")).toEqual([[1, 3, "window"]]);
    const slow = await createTreeSitterChunker({ parseTimeoutMs: 0 });
    const prepared = await prepareFile(
      slow,
      "src/a.ts",
      bytes("export const a = 1;\n".repeat(200)),
    );
    expect(prepared.kind === "chunks" && prepared.chunks.every((c) => c.kind === "window")).toBe(
      true,
    );
  });

  it("skips binary, generated and empty content, and refuses bytes that are not UTF-8", async () => {
    expect(await prepareFile(chunker, "src/a.ts", new Uint8Array([97, 0, 98]))).toEqual({
      kind: "skip",
      reason: "binary",
    });
    expect(await prepareFile(chunker, "src/a.ts", new Uint8Array([0xc3, 0x28]))).toEqual({
      kind: "skip",
      reason: "binary",
    });
    expect(
      await prepareFile(chunker, "api/x.go", bytes("// Code generated by x. DO NOT EDIT.\n")),
    ).toEqual({ kind: "skip", reason: "generated" });
    expect(await prepareFile(chunker, "src/a.ts", bytes("\n\n"))).toEqual({
      kind: "skip",
      reason: "empty",
    });
    expect(await prepareFile(chunker, "logo.png", bytes("x"))).toEqual({
      kind: "skip",
      reason: "unsupported",
    });
  });

  it("hashes each chunk's text and drops a leading byte-order mark", async () => {
    const prepared = await prepareFile(chunker, "src/a.ts", bytes("﻿export const a = 1;\n"));
    if (prepared.kind !== "chunks") throw new Error("expected chunks");
    const [chunk] = prepared.chunks;
    expect(chunk?.text).toBe("export const a = 1;");
    expect(chunk?.contentSha256).toBe(
      createHash("sha256").update("export const a = 1;").digest("hex"),
    );
    expect(prepared.language).toBe("typescript");
  });
});

describe("gitBlobSha", () => {
  it("is git's blob id (git hash-object)", () => {
    // `printf 'hello\n' | git hash-object --stdin`
    expect(gitBlobSha(bytes("hello\n"))).toBe("ce013625030ba8dba906f756967f9e9ca394464a");
    expect(gitBlobSha(new Uint8Array())).toBe("e69de29bb2d1d6434b8b29ae775ad8c2e48c5391");
  });
});

describe("deterministicEmbedder (tests and the benchmark; never a configured provider)", () => {
  it("returns the same unit vector for the same text, a different one otherwise, and counts tokens", async () => {
    const embedder = deterministicEmbedder({ dimensions: 8 });
    const a = await embedder.embed({ inputs: ["alpha", "beta", "alpha"] });
    expect(a.vectors[0]).toEqual(a.vectors[2]);
    expect(a.vectors[0]).not.toEqual(a.vectors[1]);
    for (const v of a.vectors) {
      expect(v).toHaveLength(8);
      expect(Math.hypot(...v)).toBeCloseTo(1, 10);
    }
    expect(a.usage?.inputTokens).toBeGreaterThan(0);
    expect(a.provider).toBe("fake");
    expect(embedder.calls).toBe(1);
  });

  it("refuses a batch over its size and a width over the index", async () => {
    const embedder = deterministicEmbedder({ dimensions: 4, maxBatch: 2 });
    await expect(embedder.embed({ inputs: ["a", "b", "c"] })).rejects.toThrow();
    expect(() => deterministicEmbedder({ dimensions: INDEX_VECTOR_DIMENSIONS + 1 })).toThrow();
  });

  it("waits the simulated latency per call", async () => {
    const embedder = deterministicEmbedder({ dimensions: 4, latencyMs: 30 });
    const started = Date.now();
    await embedder.embed({ inputs: ["a"] });
    expect(Date.now() - started).toBeGreaterThanOrEqual(25);
  });
});
