import { randomBytes } from "node:crypto";
import { link, lstat, mkdir, open, unlink } from "node:fs/promises";
import { dirname, isAbsolute, join } from "node:path";
import { ENV_SAFE } from "@rocky-reviews/forge-github";

/**
 * Hands the GitHub App's credentials to the self-hoster (P3-1, ADR 0008): written once, as a
 * `.env`-format file with mode 0600, atomically, never overwriting anything. The server never
 * reads this file back and never logs or renders its contents; the human moves the values into
 * their secret manager (or `.env` in development) and deletes it.
 */

export interface GitHubAppSecrets {
  appId: number;
  /** Omitted from the file when GitHub returned no usable slug. */
  slug: string | undefined;
  clientId: string;
  clientSecret: string;
  privateKeyPem: string;
  webhookSecret: string;
  /** `generated`: GitHub's secret was missing or weak; the human must set this one on GitHub. */
  webhookSecretSource: "github" | "generated";
}

export type CredentialsFileFailure =
  "exists" | "unsafe_directory" | "not_absolute" | "invalid_value" | "unsupported_platform" | "io";

/** Fixed messages; never the path's contents or a value. */
export class CredentialsFileError extends Error {
  override readonly name = "CredentialsFileError";
  constructor(
    readonly reason: CredentialsFileFailure,
    readonly errno?: string,
  ) {
    super(`credentials file: ${reason}${errno === undefined ? "" : ` (${errno})`}`);
  }
}

const PEM =
  /^-----BEGIN (RSA )?PRIVATE KEY-----\n(?:[A-Za-z0-9+/=]{1,76}\n)+-----END \1PRIVATE KEY-----\n?$/;

/** One value, single-quoted; only `ENV_SAFE` characters, so the quotes cannot be closed early. */
const quoted = (value: string): string => {
  if (!ENV_SAFE.test(value)) throw new CredentialsFileError("invalid_value");
  return `'${value}'`;
};

/**
 * The file's text. Every value is re-checked here (defence in depth over the conversion schema)
 * so that nothing GitHub returns can add a line, a quote or an expansion, and single-quoted, so
 * the file reads the same through Node's `--env-file`/`util.parseEnv` and a shell's `source`.
 * The PEM is the only multi-line value (base64 lines, no quote can occur in it).
 */
export const credentialsEnvText = (s: GitHubAppSecrets): string => {
  if (!Number.isSafeInteger(s.appId) || s.appId < 1)
    throw new CredentialsFileError("invalid_value");
  if (!PEM.test(s.privateKeyPem)) throw new CredentialsFileError("invalid_value");
  const pem = s.privateKeyPem.endsWith("\n") ? s.privateKeyPem : `${s.privateKeyPem}\n`;
  const lines = [
    "# Rocky Reviews GitHub App credentials (P3-1). Secret: move these values into your secret",
    "# manager (or .env in development), then delete this file. See docs/runbooks/h3-create-github-app.md.",
    `GITHUB_APP_ID='${s.appId}'`,
    ...(s.slug === undefined
      ? [
          "# GITHUB_APP_SLUG: GitHub returned none; see the app's page under your GitHub App settings.",
        ]
      : [`GITHUB_APP_SLUG=${quoted(s.slug)}`]),
    `GITHUB_APP_CLIENT_ID=${quoted(s.clientId)}`,
    `GITHUB_APP_CLIENT_SECRET=${quoted(s.clientSecret)}`,
    ...(s.webhookSecretSource === "generated"
      ? [
          "# GITHUB_WEBHOOK_SECRET was generated by Rocky because the one from GitHub was missing or too weak:",
          "# paste it into the app's settings on GitHub (General → Webhook secret) before installing.",
        ]
      : []),
    `GITHUB_WEBHOOK_SECRET=${quoted(s.webhookSecret)}`,
    `GITHUB_APP_PRIVATE_KEY='${pem}'`,
    "",
  ];
  return lines.join("\n");
};

const errnoOf = (error: unknown): string | undefined =>
  typeof error === "object" && error !== null && "code" in error && typeof error.code === "string"
    ? error.code
    : undefined;

const exists = async (path: string): Promise<boolean> => {
  try {
    await lstat(path);
    return true;
  } catch (error) {
    if (errnoOf(error) === "ENOENT") return false;
    throw new CredentialsFileError("io", errnoOf(error));
  }
};

/** The directory must be a real directory, owned by us, and not group- or world-writable. */
const checkDirectory = async (dir: string): Promise<void> => {
  let st;
  try {
    st = await lstat(dir);
  } catch (error) {
    throw new CredentialsFileError("io", errnoOf(error));
  }
  const uid = process.getuid?.();
  if (!st.isDirectory() || (st.mode & 0o022) !== 0 || (uid !== undefined && st.uid !== uid)) {
    throw new CredentialsFileError("unsafe_directory");
  }
};

/**
 * Refuses early (before the code is exchanged, so GitHub's one-time response is not lost) when
 * the target exists or its directory is unsafe. Creates nothing.
 */
export const checkCredentialsTarget = async (file: string): Promise<void> => {
  // POSIX modes are what protect the file; Windows ignores them (ACLs instead).
  if (process.platform === "win32") throw new CredentialsFileError("unsupported_platform");
  if (!isAbsolute(file)) throw new CredentialsFileError("not_absolute");
  if (await exists(file)) throw new CredentialsFileError("exists");
  const dir = dirname(file);
  if (await exists(dir)) await checkDirectory(dir);
};

/**
 * Writes `text` to `file` exactly once: a temporary file in the same directory is created with
 * `O_CREAT|O_EXCL` (never follows a symlink) and mode 0600 (re-applied with fchmod, whatever the
 * umask), fsynced, then hard-linked to `file`. `link` fails if anything (even a dangling symlink)
 * already sits there, so the target is never overwritten and concurrent writers cannot both win.
 * The directory is created 0700 when missing and refused when group/world-writable.
 */
export const writeCredentialsOnce = async (file: string, text: string): Promise<void> => {
  await checkCredentialsTarget(file);
  const dir = dirname(file);
  try {
    await mkdir(dir, { recursive: true, mode: 0o700 });
  } catch (error) {
    throw new CredentialsFileError("io", errnoOf(error));
  }
  await checkDirectory(dir);

  const tmp = join(dir, `.rocky-credentials-${randomBytes(12).toString("hex")}.tmp`);
  try {
    const handle = await open(tmp, "wx", 0o600);
    try {
      await handle.chmod(0o600);
      await handle.writeFile(text, "utf8");
      await handle.sync();
    } finally {
      await handle.close();
    }
    try {
      await link(tmp, file);
    } catch (error) {
      throw errnoOf(error) === "EEXIST"
        ? new CredentialsFileError("exists")
        : new CredentialsFileError("io", errnoOf(error));
    }
  } catch (error) {
    if (error instanceof CredentialsFileError) throw error;
    throw new CredentialsFileError("io", errnoOf(error));
  } finally {
    await unlink(tmp).catch(() => undefined);
  }
};
