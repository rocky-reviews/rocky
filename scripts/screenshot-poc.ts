import { chromium, type Page } from "@playwright/test";
import { mkdir, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";

/**
 * P0-8: captures every state of design-poc/index.html at 3 widths x light/dark.
 * Output is the visual reference for Phase 6 (docs/design/poc/).
 * Run: pnpm design:poc-screenshots
 */

const POC = pathToFileURL(resolve("design-poc/index.html")).href;
const OUT = resolve("docs/design/poc");
const WIDTHS = [
  { width: 375, height: 812 },
  { width: 1024, height: 900 },
  { width: 1440, height: 900 },
] as const;
const MODES = ["light", "dark"] as const;

type State = { id: string; title: string; run: (page: Page) => Promise<void> };

const firstDraftButton = (page: Page, label: string) =>
  page.locator(".draft").first().getByRole("button", { name: label });

const STATES: State[] = [
  { id: "01-briefing", title: "Briefing and change map (landing state)", run: async () => {} },
  {
    id: "02-file-critical",
    title: "Riskiest file with AI flags and draft findings",
    run: async (page) => {
      await page.keyboard.press("k");
    },
  },
  {
    id: "03-draft-dismiss",
    title: "Dismissing a draft asks for a reason",
    run: async (page) => {
      await page.keyboard.press("k");
      await firstDraftButton(page, "Dismiss").click();
    },
  },
  {
    id: "04-draft-accepted",
    title: "Accepted draft becomes your pending comment",
    run: async (page) => {
      await page.keyboard.press("k");
      await firstDraftButton(page, "Accept").click();
    },
  },
  {
    id: "05-draft-edit",
    title: "Editing a draft before accepting it",
    run: async (page) => {
      await page.keyboard.press("k");
      await firstDraftButton(page, "Edit").click();
    },
  },
  {
    id: "06-own-comment",
    title: "Writing your own comment on a line",
    run: async (page) => {
      await page.keyboard.press("k");
      await page.locator('[data-act="compose"][data-line="10"]').click();
      await page.locator("#compose-box").fill("Should this TTL come from config?");
    },
  },
  {
    id: "07-noise",
    title: "Noise file shown as an AI summary",
    run: async (page) => {
      for (let i = 0; i < 8; i += 1) await page.keyboard.press("k");
    },
  },
  {
    id: "08-ask",
    title: "Ask panel with a cited answer",
    run: async (page) => {
      if (!(await page.locator(".panel").isVisible())) return;
      await page.getByRole("button", { name: "✦ Ask" }).click();
      await page.getByRole("button", { name: "What does an attacker need to exploit F1?" }).click();
      await page.waitForSelector(".chat-a .cite");
    },
  },
  {
    id: "09-finish",
    title: "Finish review modal",
    run: async (page) => {
      await page.keyboard.press("k");
      await firstDraftButton(page, "Accept").click();
      await page.getByRole("button", { name: /Finish review/ }).click();
    },
  },
  {
    id: "10-shortcuts",
    title: "Keyboard shortcuts help",
    run: async (page) => {
      await page.keyboard.press("?");
    },
  },
];

const browser = await chromium.launch();
await mkdir(OUT, { recursive: true });
const index: string[] = [
  "# POC visual reference",
  "",
  "Generated by `pnpm design:poc-screenshots` from `design-poc/index.html` (task P0-8).",
  "Phase 6 compares the real app against these. Panels hidden at a width are hidden in the POC too",
  "(right panel < 1180 px, sidebar < 760 px).",
  "",
  "| State | " + WIDTHS.flatMap((w) => MODES.map((m) => `${w.width} ${m}`)).join(" | ") + " |",
  "|---|" + WIDTHS.flatMap(() => MODES.map(() => "---")).join("|") + "|",
];

for (const state of STATES) {
  const cells: string[] = [];
  for (const size of WIDTHS) {
    for (const mode of MODES) {
      const context = await browser.newContext({ viewport: size, colorScheme: mode });
      const page = await context.newPage();
      await page.goto(POC);
      await page.evaluate(() => localStorage.clear());
      await page.reload();
      await page.addStyleTag({ content: "*{animation:none!important;transition:none!important}" });
      await state.run(page);
      await page.waitForTimeout(150);
      const file = `${state.id}-${size.width}-${mode}.png`;
      await page.screenshot({ path: join(OUT, file) });
      cells.push(`[img](${file})`);
      await context.close();
    }
  }
  index.push(`| ${state.title} | ${cells.join(" | ")} |`);
}

await browser.close();
await writeFile(join(OUT, "README.md"), index.join("\n") + "\n");
console.log(`wrote ${STATES.length * WIDTHS.length * MODES.length} screenshots to ${OUT}`);
