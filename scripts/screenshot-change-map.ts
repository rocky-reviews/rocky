import { chromium, type Browser } from "@playwright/test";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { renderChangeMap, type ChangeMapSource } from "../packages/renderer/src/index.js";
import {
  deepNesting,
  longLabels,
  pr847,
  singleNode,
  wideFanOut,
} from "../packages/renderer/src/test-support.js";

/**
 * P5-1: the change map in light and dark, next to the POC's diagram (design-poc/index.html),
 * plus every golden shape. The map is drawn the way the web app will draw it: the SVG inline,
 * styled by tokens.css and the renderer's change-map.css only. Output: docs/design/change-map/.
 * Run: pnpm design:change-map-screenshots
 */

const OUT = resolve("docs/design/change-map");
const POC = pathToFileURL(resolve("design-poc/index.html")).href;
const MODES = ["light", "dark"] as const;
type Mode = (typeof MODES)[number];

const SHAPES: Record<string, () => ChangeMapSource> = {
  "pr-847": pr847,
  "single-node": singleNode,
  "wide-fan-out": wideFanOut,
  "deep-nesting": deepNesting,
  "long-labels": longLabels,
  unavailable: () => ({ findings: [], provenance: { graphUnavailable: { reason: "timeout" } } }),
};

const styles = [
  await readFile(resolve("apps/web/src/styles/tokens.css"), "utf8"),
  await readFile(resolve("packages/renderer/src/change-map.css"), "utf8"),
  "body { margin: 0; padding: 16px; background: var(--panel); }",
  "*, * > * { animation: none !important; }",
].join("\n");

const page = (mode: Mode, body: string) =>
  `<!doctype html><html data-mode="${mode}"><head><meta charset="utf-8"><style>${styles}</style></head><body>${body}</body></html>`;

const shoot = async (browser: Browser, mode: Mode, html: string, file: string): Promise<Buffer> => {
  const context = await browser.newContext({
    viewport: { width: 1600, height: 900 },
    colorScheme: mode,
  });
  const tab = await context.newPage();
  await tab.setContent(html);
  const shot = await tab
    .locator("body > *")
    .first()
    .screenshot({ path: join(OUT, file) });
  await context.close();
  return shot;
};

const pocDiagram = async (browser: Browser, mode: Mode): Promise<Buffer> => {
  const context = await browser.newContext({
    viewport: { width: 1440, height: 900 },
    colorScheme: mode,
  });
  const tab = await context.newPage();
  await tab.goto(POC);
  await tab.evaluate(() => localStorage.clear());
  await tab.reload();
  await tab.addStyleTag({ content: "*{animation:none!important;transition:none!important}" });
  const shot = await tab
    .locator("svg.diagram")
    .screenshot({ path: join(OUT, `poc-diagram-${mode}.png`) });
  await context.close();
  return shot;
};

const browser = await chromium.launch();
await mkdir(OUT, { recursive: true });
const index = [
  "# Change map: visual evidence (P5-1)",
  "",
  "Generated by `pnpm design:change-map-screenshots` (`scripts/screenshot-change-map.ts`). The",
  "renderer's SVG is drawn inline with `tokens.css` and `change-map.css` only, as the web app will",
  "draw it. The compare images put the POC's diagram (`design-poc/index.html`) above Rocky's",
  "render of the same PR (fixture pr-847).",
  "",
  "| Shape | light | dark |",
  "|---|---|---|",
];

for (const mode of MODES) {
  const poc = await pocDiagram(browser, mode);
  const ours = await shoot(
    browser,
    mode,
    page(mode, renderChangeMap(pr847()).svg),
    `pr-847-${mode}.png`,
  );
  const img = (png: Buffer) => `<img src="data:image/png;base64,${png.toString("base64")}">`;
  await shoot(
    browser,
    mode,
    page(
      mode,
      `<div style="display:grid;gap:12px;font:600 13px var(--font-ui);color:var(--muted);width:max-content">` +
        `<div>POC (design-poc/index.html)</div>${img(poc)}` +
        `<div>Rocky (packages/renderer, pr-847)</div>${img(ours)}</div>`,
    ),
    `compare-${mode}.png`,
  );
}
index.push("| POC vs Rocky, pr-847 | [img](compare-light.png) | [img](compare-dark.png) |");

for (const [name, build] of Object.entries(SHAPES)) {
  const cells: string[] = [];
  for (const mode of MODES) {
    const file = `${name}-${mode}.png`;
    if (name !== "pr-847")
      await shoot(browser, mode, page(mode, renderChangeMap(build()).svg), file);
    cells.push(`[img](${file})`);
  }
  index.push(`| ${name} | ${cells.join(" | ")} |`);
}

await browser.close();
await writeFile(join(OUT, "README.md"), index.join("\n") + "\n");
console.log(`wrote change-map screenshots to ${OUT}`);
